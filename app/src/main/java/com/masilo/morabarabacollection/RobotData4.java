    /**
     * Tries to find a match in moveData and execute a two-step move:
     * click source circle -> click destination circle.
     */
    public boolean usedMoveData() {
        map = Arrays.toString(robot.panel.mapArray);

        for (String[] datum : moveData) {
            String storedMap = datum[0];
            int fromIndex = Integer.parseInt(datum[1]);
            int toIndex = Integer.parseInt(datum[2]);

            if (storedMap.equals(map)) {
                // Perform two clicks: source then destination
                robot.pieceClicked(robot.getCircleArray()[fromIndex].getPiece());
                robot.circleClicked(robot.getCircleArray()[toIndex]);

                return true;
            }
        }

        return false;
    }
